# apply-env.ps1 - reads GEMINI_API_KEY and GROQ_API_KEY (gsk_...) from .env (project root) and writes Assets/Scripts/GeminiKeyLocal.ts, the local module the Lens reads.
# Windows PowerShell, no installs. Works with an empty key (writes an empty export). NEVER prints the key (only "set, N chars" or "empty").
# Usage (from the project root):  powershell -ExecutionPolicy Bypass -File tools/apply-env.ps1
# Optional: -EnvFile <path> -OutFile <path> (for tests).
param(
  [string]$EnvFile = "",
  [string]$OutFile = ""
)
$root = Split-Path -Parent $PSScriptRoot
if ($EnvFile -eq "") { $EnvFile = Join-Path $root ".env" }
if ($OutFile -eq "") { $OutFile = Join-Path $root "Assets/Scripts/GeminiKeyLocal.ts" }
$key = ""
$groq = ""
if (Test-Path $EnvFile) {
  foreach ($line in Get-Content -LiteralPath $EnvFile) {
    $t = $line.Trim()
    if ($t.StartsWith("#") -or $t -eq "") { continue }
    if ($t -match '^GEMINI_API_KEY\s*=\s*(.*)$') {
      $key = $Matches[1].Trim().Trim('"').Trim("'")
    }
    if ($t -match '^GROQ_API_KEY\s*=\s*(.*)$') {
      $groq = $Matches[1].Trim().Trim('"').Trim("'")
    }
  }
} else {
  Write-Host ".env not found: copy .env.example to .env first. Writing an empty key."
}
# only characters a Google API key can contain go into the TypeScript string (nothing else can break the file)
if ($key -notmatch '^[A-Za-z0-9._\-]*$') {
  Write-Host "GEMINI_API_KEY has unexpected characters: ignored (empty key written)."
  $key = ""
}
if ($groq -notmatch '^[A-Za-z0-9._\-]*$') {
  Write-Host "GROQ_API_KEY has unexpected characters: ignored (empty key written)."
  $groq = ""
}
$content = @"
// GeminiKeyLocal.ts - GENERATED by tools/apply-env.ps1 from .env. Do not edit, do not commit a real key.
// The committed version is an empty stub so a fresh clone compiles; after running the script mark it local-only:
//   git update-index --skip-worktree Assets/Scripts/GeminiKeyLocal.ts
export const GEMINI_KEY_LOCAL: string = "$key"
export const GROQ_KEY_LOCAL: string = "$groq"
"@
Set-Content -LiteralPath $OutFile -Value $content -Encoding UTF8
if ($key.Length -gt 0) { Write-Host ("GeminiKeyLocal.ts written: key set, " + $key.Length + " chars (value not shown)") } else { Write-Host "GeminiKeyLocal.ts written: Gemini key empty" }
if ($groq.Length -gt 0) { Write-Host ("Groq key set, " + $groq.Length + " chars (value not shown)") } else { Write-Host "Groq key empty" }
# best effort: keep the generated file out of "git status" (silent when this is not a git checkout)
try { & git -C $root update-index --skip-worktree "Assets/Scripts/GeminiKeyLocal.ts" 2>$null | Out-Null } catch { }
